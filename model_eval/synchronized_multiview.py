"""Utilities for synchronizing overlapping pinhole views during diffusion.

The views must share a camera centre and differ only by a known camera-local
rotation.  This is exactly the contract of the trajectories generated by
``generate_nerfstudio14_trajectories.py``.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from collections.abc import Sequence

import torch
import torch.nn.functional as F


@dataclass(frozen=True)
class LatentReprojection:
    """One directed target-pixel to source-view latent reprojection."""

    source: int
    target: int
    grid: torch.Tensor
    valid: torch.Tensor
    overlap_fraction: float
    geometric_overlap_fraction: float | None = None


def yaw_rotation(yaw_degrees: float, *, device: torch.device) -> torch.Tensor:
    """Return the OpenGL local-camera yaw convention used by the manifests."""
    angle = math.radians(yaw_degrees)
    c, s = math.cos(angle), math.sin(angle)
    return torch.tensor(
        ((c, 0.0, -s), (0.0, 1.0, 0.0), (s, 0.0, c)),
        device=device,
        dtype=torch.float32,
    )


def perspective_reprojection_grid_rotations(
    height: int,
    width: int,
    fov_degrees: float,
    *,
    source_rotation: torch.Tensor | Sequence[Sequence[float]],
    target_rotation: torch.Tensor | Sequence[Sequence[float]],
    device: torch.device,
    dtype: torch.dtype = torch.float32,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Map target pixels into a source pinhole under an arbitrary 3D rotation.

    Both cameras share a centre.  Rotations are camera-local OpenGL C2W
    rotations, so ``R_source.T @ R_target`` maps target camera rays into the
    source camera.  This supports the pitched upper/lower frustums as well as
    the horizontal yaw ring.
    """
    if height <= 0 or width <= 0:
        raise ValueError(f"height and width must be positive, got {(height, width)}")
    if not math.isfinite(fov_degrees) or not 0.0 < fov_degrees < 180.0:
        raise ValueError(f"fov_degrees must be in (0, 180), got {fov_degrees}")

    # Validate camera metadata in CPU float64.  Performing this tiny matrix
    # product on Hopper may use TF32, whose rounding is larger than the strict
    # metadata tolerance and can reject an otherwise valid rotation.
    source_cpu = torch.as_tensor(source_rotation, device="cpu", dtype=torch.float64)
    target_cpu = torch.as_tensor(target_rotation, device="cpu", dtype=torch.float64)
    if source_cpu.shape == (4, 4):
        source_cpu = source_cpu[:3, :3]
    if target_cpu.shape == (4, 4):
        target_cpu = target_cpu[:3, :3]
    if source_cpu.shape != (3, 3) or target_cpu.shape != (3, 3):
        raise ValueError(f"rotations must be 3x3 or 4x4, got {source_cpu.shape} and {target_cpu.shape}")
    identity = torch.eye(3, dtype=torch.float64)
    if not torch.allclose(source_cpu.T @ source_cpu, identity, atol=1e-7, rtol=1e-7):
        raise ValueError("source_rotation is not orthonormal")
    if not torch.allclose(target_cpu.T @ target_cpu, identity, atol=1e-7, rtol=1e-7):
        raise ValueError("target_rotation is not orthonormal")
    source = source_cpu.to(device=device, dtype=torch.float32)
    target = target_cpu.to(device=device, dtype=torch.float32)

    y = torch.arange(height, device=device, dtype=torch.float32) + 0.5
    x = torch.arange(width, device=device, dtype=torch.float32) + 0.5
    yy, xx = torch.meshgrid(y, x, indexing="ij")
    focal = (width / 2.0) / math.tan(math.radians(fov_degrees) / 2.0)
    rays_target = torch.stack(
        ((xx - width / 2.0) / focal, -(yy - height / 2.0) / focal, -torch.ones_like(xx)),
        dim=-1,
    )
    relative = source.T @ target
    rays_source = torch.einsum("ij,hwj->hwi", relative, rays_target)
    depth = -rays_source[..., 2]
    source_x = focal * (rays_source[..., 0] / depth.clamp_min(1e-8)) + width / 2.0
    source_y = focal * (-rays_source[..., 1] / depth.clamp_min(1e-8)) + height / 2.0
    valid = (
        (depth > 0)
        & (source_x >= 0.0)
        & (source_x < width)
        & (source_y >= 0.0)
        & (source_y < height)
    )
    grid = torch.stack((2.0 * source_x / width - 1.0, 2.0 * source_y / height - 1.0), dim=-1)
    return grid.to(dtype=dtype), valid


def perspective_reprojection_grid(
    height: int,
    width: int,
    fov_degrees: float,
    *,
    source_yaw_degrees: float,
    target_yaw_degrees: float,
    device: torch.device,
    dtype: torch.dtype = torch.float32,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Map target-view pixels to a source view with the same camera centre.

    Returns a grid suitable for ``grid_sample(..., align_corners=False)`` and
    a validity mask.  The camera convention matches the generated OpenGL C2W
    trajectories: +X right, +Y up, and -Z forward.
    """
    return perspective_reprojection_grid_rotations(
        height,
        width,
        fov_degrees,
        source_rotation=yaw_rotation(source_yaw_degrees, device=device),
        target_rotation=yaw_rotation(target_yaw_degrees, device=device),
        device=device,
        dtype=dtype,
    )


def build_latent_reprojection_graph(
    rotations: Sequence[torch.Tensor | Sequence[Sequence[float]]],
    height: int,
    width: int,
    fov_degrees: float,
    *,
    device: torch.device,
    dtype: torch.dtype,
    minimum_overlap_fraction: float = 0.02,
) -> list[LatentReprojection]:
    """Precompute every useful directed overlap in a multiview camera rig."""
    if len(rotations) < 2:
        raise ValueError("at least two rotations are required")
    if not 0.0 <= minimum_overlap_fraction < 1.0:
        raise ValueError("minimum_overlap_fraction must be in [0, 1)")
    result: list[LatentReprojection] = []
    for target_index, target_rotation in enumerate(rotations):
        for source_index, source_rotation in enumerate(rotations):
            if source_index == target_index:
                continue
            grid, valid = perspective_reprojection_grid_rotations(
                height,
                width,
                fov_degrees,
                source_rotation=source_rotation,
                target_rotation=target_rotation,
                device=device,
                dtype=dtype,
            )
            overlap = float(valid.float().mean().item())
            if overlap >= minimum_overlap_fraction:
                result.append(
                    LatentReprojection(
                        source_index,
                        target_index,
                        grid,
                        valid,
                        overlap,
                        geometric_overlap_fraction=overlap,
                    )
                )
    if not result:
        raise ValueError("camera rig has no overlapping frustums")
    covered_targets = {edge.target for edge in result}
    if covered_targets != set(range(len(rotations))):
        missing = sorted(set(range(len(rotations))) - covered_targets)
        raise ValueError(f"camera rig leaves target views without overlap: {missing}")
    return result


def _vae_temporal_consensus_mask(
    masks: torch.Tensor,
    *,
    scale_factor: int,
    minimum_fraction: float,
) -> torch.Tensor:
    """Compress RGB-frame validity masks with Wan's ``1 + scale*n`` layout."""
    if masks.ndim != 3:
        raise ValueError(f"masks must have shape (T,H,W), got {tuple(masks.shape)}")
    if scale_factor <= 0:
        raise ValueError("scale_factor must be positive")
    if not 0.0 <= minimum_fraction <= 1.0:
        raise ValueError("minimum_fraction must be in [0, 1]")
    if scale_factor == 1:
        return masks.to(torch.bool)
    if (masks.shape[0] - 1) % scale_factor:
        raise ValueError(
            f"RGB frame count must be 1 + {scale_factor}*n, got {masks.shape[0]}"
        )
    output = [masks[:1].to(torch.float32)]
    for start in range(1, masks.shape[0], scale_factor):
        output.append(masks[start : start + scale_factor].to(torch.float32).mean(dim=0, keepdim=True))
    return (torch.cat(output, dim=0) >= minimum_fraction).to(torch.bool)


def build_depth_aware_latent_reprojection_graph(
    rotations: Sequence[torch.Tensor | Sequence[Sequence[float]]],
    depths: torch.Tensor,
    height: int,
    width: int,
    fov_degrees: float,
    *,
    device: torch.device,
    dtype: torch.dtype,
    opacity: torch.Tensor | None = None,
    vae_temporal_scale: int = 4,
    minimum_overlap_fraction: float = 0.02,
    minimum_depth_overlap_fraction: float = 0.002,
    depth_relative_tolerance: float = 0.08,
    opacity_threshold: float = 0.05,
    spatial_valid_fraction: float = 0.5,
    temporal_valid_fraction: float = 0.5,
) -> list[LatentReprojection]:
    """Build an occlusion-aware same-centre spherical correspondence graph.

    ``depths`` contains radial renderer distances with shape ``(V,T,H,W)``.
    Relative rotations provide the exact ray correspondence between same-centre
    frustums.  A correspondence is retained only when the radial distances agree,
    which rejects disocclusions and contradictory geometry before consensus is
    applied to latents or noise predictions.
    """
    if depths.ndim != 4 or depths.shape[0] != len(rotations):
        raise ValueError(
            f"depths must have shape (V,T,H,W) for {len(rotations)} views, got {tuple(depths.shape)}"
        )
    if depths.shape[-2] <= 0 or depths.shape[-1] <= 0:
        raise ValueError("depth maps must be non-empty")
    if opacity is not None and opacity.shape != depths.shape:
        raise ValueError(
            f"opacity must match depths {tuple(depths.shape)}, got {tuple(opacity.shape)}"
        )
    if not 0.0 <= minimum_depth_overlap_fraction < 1.0:
        raise ValueError("minimum_depth_overlap_fraction must be in [0, 1)")
    if not 0.0 <= depth_relative_tolerance:
        raise ValueError("depth_relative_tolerance must be non-negative")
    if not 0.0 <= opacity_threshold <= 1.0:
        raise ValueError("opacity_threshold must be in [0, 1]")
    if not 0.0 <= spatial_valid_fraction <= 1.0:
        raise ValueError("spatial_valid_fraction must be in [0, 1]")

    depths = depths.to(device=device, dtype=torch.float32)
    opacity = opacity.to(device=device, dtype=torch.float32) if opacity is not None else None
    depth_height, depth_width = depths.shape[-2:]
    geometric_graph = build_latent_reprojection_graph(
        rotations,
        height,
        width,
        fov_degrees,
        device=device,
        dtype=dtype,
        minimum_overlap_fraction=minimum_overlap_fraction,
    )
    result: list[LatentReprojection] = []
    for edge in geometric_graph:
        depth_grid, geometric_valid = perspective_reprojection_grid_rotations(
            depth_height,
            depth_width,
            fov_degrees,
            source_rotation=rotations[edge.source],
            target_rotation=rotations[edge.target],
            device=device,
            dtype=torch.float32,
        )
        frame_grids = depth_grid.unsqueeze(0).expand(depths.shape[1], -1, -1, -1)
        sampled_source_depth = F.grid_sample(
            depths[edge.source].unsqueeze(1),
            frame_grids,
            mode="bilinear",
            padding_mode="zeros",
            align_corners=False,
        ).squeeze(1)
        target_depth = depths[edge.target]
        denominator = torch.maximum(sampled_source_depth.abs(), target_depth.abs()).clamp_min(1e-6)
        relative_error = (sampled_source_depth - target_depth).abs() / denominator
        valid = (
            geometric_valid.unsqueeze(0)
            & torch.isfinite(sampled_source_depth)
            & torch.isfinite(target_depth)
            & (sampled_source_depth > 0)
            & (target_depth > 0)
            & (relative_error <= depth_relative_tolerance)
        )
        if opacity is not None:
            sampled_source_opacity = F.grid_sample(
                opacity[edge.source].unsqueeze(1),
                frame_grids,
                mode="bilinear",
                padding_mode="zeros",
                align_corners=False,
            ).squeeze(1)
            valid &= sampled_source_opacity >= opacity_threshold
            valid &= opacity[edge.target] >= opacity_threshold

        valid_latent = F.interpolate(
            valid.to(torch.float32).unsqueeze(1),
            size=(height, width),
            mode="area",
        ).squeeze(1)
        valid_latent = valid_latent >= spatial_valid_fraction
        valid_latent = _vae_temporal_consensus_mask(
            valid_latent,
            scale_factor=vae_temporal_scale,
            minimum_fraction=temporal_valid_fraction,
        )
        depth_overlap = float(valid_latent.to(torch.float32).mean().item())
        if depth_overlap < minimum_depth_overlap_fraction:
            continue
        result.append(
            LatentReprojection(
                source=edge.source,
                target=edge.target,
                grid=edge.grid,
                valid=valid_latent,
                overlap_fraction=depth_overlap,
                geometric_overlap_fraction=edge.geometric_overlap_fraction,
            )
        )

    if not result:
        raise ValueError("depth/occlusion filtering removed every spherical overlap")
    covered_targets = {edge.target for edge in result}
    if covered_targets != set(range(len(rotations))):
        missing = sorted(set(range(len(rotations))) - covered_targets)
        raise ValueError(f"depth-aware graph leaves target views without overlap: {missing}")
    return result


def validate_reprojection_graph(
    graph: Sequence[LatentReprojection],
    view_names: Sequence[str],
    *,
    required_bidirectional_pairs: Sequence[tuple[str, str]] = (),
) -> dict[str, float]:
    """Fail closed unless the graph is connected and contains required loops."""
    if len(view_names) < 2 or len(set(view_names)) != len(view_names):
        raise ValueError("view_names must contain at least two unique names")
    index = {name: position for position, name in enumerate(view_names)}
    adjacency = {position: set() for position in range(len(view_names))}
    directed = set()
    for edge in graph:
        if edge.source not in adjacency or edge.target not in adjacency:
            raise ValueError(f"graph edge is outside the named rig: {edge}")
        adjacency[edge.source].add(edge.target)
        adjacency[edge.target].add(edge.source)
        directed.add((edge.source, edge.target))
    seen = {0}
    frontier = [0]
    while frontier:
        current = frontier.pop()
        for neighbor in adjacency[current] - seen:
            seen.add(neighbor)
            frontier.append(neighbor)
    if len(seen) != len(view_names):
        missing = [view_names[position] for position in range(len(view_names)) if position not in seen]
        raise ValueError(f"reprojection graph is disconnected; missing={missing}")
    for first, second in required_bidirectional_pairs:
        if first not in index or second not in index:
            raise ValueError(f"required loop pair references an unknown view: {(first, second)}")
        pair = (index[first], index[second])
        if pair not in directed or pair[::-1] not in directed:
            raise ValueError(f"required bidirectional loop is absent: {first}<->{second}")
    return {
        "directed_edges": float(len(graph)),
        "mean_depth_valid_fraction": float(
            sum(edge.overlap_fraction for edge in graph) / len(graph)
        ),
        "minimum_depth_valid_fraction": float(min(edge.overlap_fraction for edge in graph)),
    }


def synchronize_latent_views(
    latents: torch.Tensor,
    graph: Sequence[LatentReprojection],
    *,
    blend: float = 0.65,
) -> tuple[torch.Tensor, dict[str, float]]:
    """Apply a global spherical consensus to ``(V,C,T,H,W)`` latents."""
    if latents.ndim != 5 or latents.shape[0] < 2:
        raise ValueError(f"latents must have shape (V,C,T,H,W), got {tuple(latents.shape)}")
    if not 0.0 <= blend <= 1.0:
        raise ValueError(f"blend must be in [0, 1], got {blend}")
    views, _, _, height, width = latents.shape
    sums = latents.clone()
    weights = torch.ones(
        (views, 1, latents.shape[2], height, width),
        device=latents.device,
        dtype=latents.dtype,
    )
    before_total = torch.zeros((), device=latents.device, dtype=torch.float32)
    before_mass = torch.zeros((), device=latents.device, dtype=torch.float32)
    for edge in graph:
        if not 0 <= edge.source < views or not 0 <= edge.target < views:
            raise ValueError(f"graph edge is outside {views} views: {edge}")
        warped = warp_video_latents(latents[edge.source], edge.grid)
        valid = edge.valid.to(device=latents.device, dtype=latents.dtype)
        if valid.shape == (height, width):
            mask = valid.view(1, 1, height, width).expand(1, latents.shape[2], -1, -1)
        elif valid.shape == (latents.shape[2], height, width):
            mask = valid.unsqueeze(0)
        else:
            raise ValueError(
                "edge validity must be spatial or spatiotemporal; "
                f"expected {(height, width)} or {(latents.shape[2], height, width)}, got {tuple(valid.shape)}"
            )
        sums[edge.target] += warped * mask
        weights[edge.target] += mask
        before_total += ((latents[edge.target] - warped).abs().float() * mask.float()).sum()
        before_mass += mask.float().sum() * latents.shape[1]
    consensus = sums / weights.clamp_min(1.0)
    result = torch.lerp(latents, consensus, blend)

    after_total = torch.zeros((), device=latents.device, dtype=torch.float32)
    after_mass = torch.zeros((), device=latents.device, dtype=torch.float32)
    for edge in graph:
        warped = warp_video_latents(result[edge.source], edge.grid)
        valid = edge.valid.to(device=latents.device, dtype=latents.dtype)
        mask = (
            valid.view(1, 1, height, width).expand(1, latents.shape[2], -1, -1)
            if valid.ndim == 2
            else valid.unsqueeze(0)
        )
        after_total += ((result[edge.target] - warped).abs().float() * mask.float()).sum()
        after_mass += mask.float().sum() * latents.shape[1]
    stats = {
        "directed_edges": float(len(graph)),
        "mean_overlap_fraction": float(sum(edge.overlap_fraction for edge in graph) / len(graph)),
        "latent_l1_before": float((before_total / before_mass.clamp_min(1.0)).item()),
        "latent_l1_after": float((after_total / after_mass.clamp_min(1.0)).item()),
    }
    return result, stats


def synchronize_low_frequency_latent_views(
    latents: torch.Tensor,
    graph: Sequence[LatentReprojection],
    *,
    kernel_size: int = 5,
    blend: float = 1.0,
) -> tuple[torch.Tensor, dict[str, float]]:
    """Close low-frequency seams while preserving each view's detail residual.

    The graph consensus is applied only to a spatially low-pass copy.  The
    original high-frequency residual is then added back unchanged, avoiding
    the edge loss caused by full latent averaging immediately before decode.
    """
    if latents.ndim != 5 or latents.shape[0] < 2:
        raise ValueError(f"latents must have shape (V,C,T,H,W), got {tuple(latents.shape)}")
    if kernel_size < 3 or kernel_size % 2 == 0:
        raise ValueError(f"kernel_size must be an odd integer >= 3, got {kernel_size}")
    views, channels, frames, height, width = latents.shape
    padding = kernel_size // 2
    if padding >= min(height, width):
        raise ValueError(
            f"kernel_size {kernel_size} is too large for latent resolution {(height, width)}"
        )
    per_frame = latents.permute(0, 2, 1, 3, 4).reshape(
        views * frames, channels, height, width
    )
    padded = F.pad(per_frame, (padding, padding, padding, padding), mode="reflect")
    low_per_frame = F.avg_pool2d(padded, kernel_size=kernel_size, stride=1)
    low_frequency = low_per_frame.reshape(views, frames, channels, height, width).permute(
        0, 2, 1, 3, 4
    )
    synchronized_low, stats = synchronize_latent_views(low_frequency, graph, blend=blend)
    high_frequency = latents - low_frequency
    result = synchronized_low + high_frequency
    preserved_error = (result - synchronized_low - high_frequency).abs().float().max()
    return result, {
        **stats,
        "low_frequency_kernel_size": float(kernel_size),
        "low_frequency_correction_l1": float(
            (synchronized_low - low_frequency).abs().float().mean().item()
        ),
        "high_frequency_residual_max_error": float(preserved_error.item()),
    }


def warp_video_latents(
    source: torch.Tensor,
    grid: torch.Tensor,
) -> torch.Tensor:
    """Warp ``(C,T,H,W)`` latents spatially without mixing video frames."""
    if source.ndim != 4:
        raise ValueError(f"source must have shape (C,T,H,W), got {tuple(source.shape)}")
    channels, frames, height, width = source.shape
    if grid.shape != (height, width, 2):
        raise ValueError(f"grid must have shape {(height, width, 2)}, got {tuple(grid.shape)}")
    source_per_frame = source.permute(1, 0, 2, 3)
    frame_grids = grid.unsqueeze(0).expand(frames, -1, -1, -1)
    warped = F.grid_sample(
        source_per_frame,
        frame_grids,
        mode="bilinear",
        padding_mode="zeros",
        align_corners=False,
    )
    return warped.permute(1, 0, 2, 3)


def synchronize_latent_pair(
    latents: torch.Tensor,
    *,
    fov_degrees: float,
    yaw_degrees: tuple[float, float],
    blend: float = 0.5,
) -> tuple[torch.Tensor, dict[str, float]]:
    """Fuse the exact spherical overlap of a two-view latent batch.

    ``latents`` has shape ``(2,C,T,H,W)``.  Each view is updated from the same
    pre-fusion tensors, so the operation is symmetric and order independent.
    """
    if latents.ndim != 5 or latents.shape[0] != 2:
        raise ValueError(f"latents must have shape (2,C,T,H,W), got {tuple(latents.shape)}")
    if not 0.0 <= blend <= 1.0:
        raise ValueError(f"blend must be in [0, 1], got {blend}")

    _, _, _, height, width = latents.shape
    grid_1_to_0, valid_1_to_0 = perspective_reprojection_grid(
        height,
        width,
        fov_degrees,
        source_yaw_degrees=yaw_degrees[1],
        target_yaw_degrees=yaw_degrees[0],
        device=latents.device,
        dtype=latents.dtype,
    )
    grid_0_to_1, valid_0_to_1 = perspective_reprojection_grid(
        height,
        width,
        fov_degrees,
        source_yaw_degrees=yaw_degrees[0],
        target_yaw_degrees=yaw_degrees[1],
        device=latents.device,
        dtype=latents.dtype,
    )
    warped_1 = warp_video_latents(latents[1], grid_1_to_0)
    warped_0 = warp_video_latents(latents[0], grid_0_to_1)

    mask_0 = valid_1_to_0.to(latents.dtype).view(1, 1, height, width)
    mask_1 = valid_0_to_1.to(latents.dtype).view(1, 1, height, width)
    before_0 = ((latents[0] - warped_1).abs() * mask_0).sum() / mask_0.sum().clamp_min(1)
    before_1 = ((latents[1] - warped_0).abs() * mask_1).sum() / mask_1.sum().clamp_min(1)

    result = latents.clone()
    result[0] = latents[0] + mask_0 * blend * (warped_1 - latents[0])
    result[1] = latents[1] + mask_1 * blend * (warped_0 - latents[1])

    after_warped_1 = warp_video_latents(result[1], grid_1_to_0)
    after_warped_0 = warp_video_latents(result[0], grid_0_to_1)
    after_0 = ((result[0] - after_warped_1).abs() * mask_0).sum() / mask_0.sum().clamp_min(1)
    after_1 = ((result[1] - after_warped_0).abs() * mask_1).sum() / mask_1.sum().clamp_min(1)
    stats = {
        "overlap_fraction_view0": float(valid_1_to_0.float().mean().item()),
        "overlap_fraction_view1": float(valid_0_to_1.float().mean().item()),
        "latent_l1_before": float(((before_0 + before_1) / 2).item()),
        "latent_l1_after": float(((after_0 + after_1) / 2).item()),
    }
    return result, stats
